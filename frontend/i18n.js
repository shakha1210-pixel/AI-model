  function currentLang() {
    const stored = localStorage.getItem("language");
    return stored && SUPPORTED_LANGS.includes(stored) ? stored : "uz";
  }

  function t(key, lang) {
    const dict = T[lang || currentLang()] || T.uz;
    return dict[key] || T.uz[key] || key;
  }

  function applyLanguage(lang) {
    if (!SUPPORTED_LANGS.includes(lang)) lang = "uz";
    localStorage.setItem("language", lang);
    document.documentElement.setAttribute("lang", lang);
    document.documentElement.setAttribute("dir", RTL_LANGS.includes(lang) ? "rtl" : "ltr");

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.dataset.i18n, lang);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder, lang));
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.setAttribute("title", t(el.dataset.i18nTitle, lang));
    });
  }

  window.I18N = {
    SUPPORTED_LANGS,
    LANG_NAMES,
    t,
    currentLang,
    applyLanguage,
  };

  // Sahifa tili darhol (chizishdan oldin) o'rnatiladi — flash bo'lmasin.
  document.documentElement.setAttribute("lang", currentLang());
  document.documentElement.setAttribute("dir", RTL_LANGS.includes(currentLang()) ? "rtl" : "ltr");

